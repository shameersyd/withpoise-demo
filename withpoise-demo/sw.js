// Bump when the app shell changes.
const APP_CACHE = "withpoise-demo-v9";

// Versioned apart from the shell: this holds the MediaPipe runtime and a model
// of several megabytes, and tying it to the app version would re-download them
// on every deploy.
const RUNTIME_CACHE = "withpoise-runtime-v1";

// Relative, so the app works wherever it is deployed rather than only at a
// domain root. The instructor trace is in here because without it there is no
// reference to compare anybody against; the video is not, because it is three
// hundred megabytes and the browser streams it in ranges.
const ASSETS = ["./", "./index.html", "./manifest.json",
                "./pose-core.js", "./instructor.js", "./follow.js", "./cues.js",
                "./coaching.js", "./reps.js", "./exercise.js", "./armature.js", "./voice.js", "./pacing.js", "./pose-worker.js",
                "./media/instructor.json", "./media/instructor-transcript.json"];

// Data that is regenerated by the offline tools, and must never be served from
// a stale copy.
//
// These were cache-first, because a `fetch()` for a JSON file has no
// `destination` and so fell through to the data branch. That meant the very
// first copy a device ever saw was the copy it kept — and the first copy this
// app's own development ever served was a trace written while the tracer was
// still running, covering a few minutes of a twenty-one minute class. A device
// in that state cannot be fixed by any amount of editing the app, which is a
// bad enough failure on its own and a worse one while debugging, because every
// fix appears to change nothing.
const FRESH_DATA = ["/media/instructor.json", "/media/instructor-transcript.json"];

const RUNTIME_HOSTS = ["cdn.jsdelivr.net", "storage.googleapis.com"];

self.addEventListener("install", (e) => {
  // One missing asset must not take the whole install down with it — the trace
  // may not have been generated yet on a fresh checkout.
  e.waitUntil(caches.open(APP_CACHE).then((c) =>
    Promise.all(ASSETS.map((a) => c.add(a).catch(() => {})))));
  self.skipWaiting();
});

self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(
    keys.filter((k) => k !== APP_CACHE && k !== RUNTIME_CACHE).map((k) => caches.delete(k)))));
  self.clients.claim();
});

async function networkFirst(request) {
  try {
    const response = await fetch(request, { cache: "no-store" });
    const copy = response.clone();
    caches.open(APP_CACHE).then((c) => c.put(request, copy));
    return response;
  } catch {
    return (await caches.match(request)) || caches.match("./index.html");
  }
}

async function cacheFirst(request, cacheName) {
  const cached = await caches.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (response && response.ok) {
    const copy = response.clone();
    caches.open(cacheName).then((c) => c.put(request, copy));
  }
  return response;
}

self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);

  if (RUNTIME_HOSTS.includes(url.hostname)) {
    e.respondWith(cacheFirst(e.request, RUNTIME_CACHE));
    return;
  }
  if (url.origin !== self.location.origin) return;

  // The video is served in ranges and must never go near the cache: a partial
  // response cached as a whole one breaks seeking in ways that look like
  // decoder bugs.
  if (url.pathname.endsWith(".mp4") || e.request.headers.has("range")) return;

  if (FRESH_DATA.some((name) => url.pathname.endsWith(name))) {
    e.respondWith(networkFirst(e.request));
    return;
  }

  const isAppCode =
    e.request.mode === "navigate" ||
    e.request.destination === "document" ||
    e.request.destination === "script" ||
    e.request.destination === "worker";

  e.respondWith(isAppCode ? networkFirst(e.request) : cacheFirst(e.request, APP_CACHE));
});
